    public static int Main(string[] args)
    {
        var cs = args[0];
        var outDir = args[1];
        var files = Directory.GetFiles(Path.Combine(cs, "gen"), "*.cs").Concat(Directory.GetFiles(Path.Combine(cs, "runtime"), "*.cs"))
            .Where(f => !f.EndsWith("Program.cs")).OrderBy(f => f, StringComparer.Ordinal).ToArray();
        var opts = new CSharpParseOptions(LanguageVersion.Latest);
        var trees = files.Select(f => CSharpSyntaxTree.ParseText(File.ReadAllText(f), opts, f)).ToList();
        var fw = Path.GetDirectoryName(typeof(object).Assembly.Location)!;
        var refs = new List<MetadataReference>();
        foreach (var f in Directory.GetFiles(fw, "*.dll"))
        {
            var b = Path.GetFileName(f);
            if (b.StartsWith("Microsoft.VisualBasic") || b == "mscorlib.dll") continue;
            try { refs.Add(MetadataReference.CreateFromFile(f)); } catch { }
        }
        comp = CSharpCompilation.Create("engine", trees, refs, new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true));
        var errs = comp.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToList();
        if (errs.Count > 0) { foreach (var e in errs.Take(10)) Console.Error.WriteLine(e); return 1; }
        foreach (var t in trees) models[t] = comp.GetSemanticModel(t);
        var gen = trees.Where(t => t.FilePath.Contains("/gen/") || Path.GetFileName(t.FilePath).StartsWith("Hand_")).ToList();

        Directory.CreateDirectory(outDir);
        CollectTypes(gen);
        var types = new StringBuilder();
        var declared = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var t in gen)
            foreach (var td in t.GetRoot().DescendantNodes().OfType<BaseTypeDeclarationSyntax>())
                TypeDecl(td, types, declared);
        var sb = new StringBuilder();
        sb.Append("# Code generated by tools/cs2x/Cs2Mojo.cs from cs/gen (the C# translation of OpenSWMM 6, swmm6_rel 88329d6). DO NOT EDIT.\n");
        sb.Append("# OpenSWMM 6 is Apache-2.0 (HydroCouple Developers), derived in part from public-domain EPA SWMM; see mojo/README.md.\n\n");
        sb.Append("from std.sys import size_of\nfrom rt.core import *\nfrom rt.crt import *\nfrom rt.str import *\nfrom rt.cont import *\nfrom rt.rlib import *\nfrom rt.fs import *\nfrom rt.streams import *\n\n");
        sb.Append(types);
        sb.Append("# ---------------------------------------------------------------- static fields\n");
        sb.Append("struct GS(Movable):\n    var __pad: Int\n").Append(statics).Append('\n');
        sb.Append("@always_inline\ndef gs() -> P[GS]:\n    return P[GS](unsafe_from_address=GS_ADDR)\n\n");
        // the static initializers in small functions: Mojo's memory grows with the size of one function
        int chunk = 0;
        for (int i = 0; i < staticInit.Count; i += 40)
        {
            sb.Append("def __static_init_").Append(chunk++).Append("() raises:\n");
            foreach (var s in staticInit.Skip(i).Take(40)) sb.Append(s);
            sb.Append("    pass\n\n");
        }
        sb.Append("def engine_static_init() raises:\n    rt_map_statics(size_of[GS]())\n");
        for (int i = 0; i < chunk; i++) sb.Append("    __static_init_").Append(i).Append("()\n");
        sb.Append('\n');
        sb.Append(TypeIdTables());
        sb.Append(funcs);
        sb.Append(Dispatchers());
        File.WriteAllText(Path.Combine(outDir, "engine.mojo"), sb.ToString());
        using (var w = new StreamWriter(Path.Combine(outDir, "..", "cs2mojo_todo.txt")))
            foreach (var kv in todos.OrderByDescending(kv => kv.Value)) w.WriteLine("{0,6}  {1}", kv.Value, kv.Key);
        using (var w = new StreamWriter(Path.Combine(outDir, "..", "cs2mojo_runtime.txt")))
            foreach (var kv in manifest) w.WriteLine(kv.Key + "\t" + kv.Value);
        Console.WriteLine("wrote engine.mojo, " + todos.Count + " TODO kinds, " + todos.Values.Sum() + " TODO sites");
        return 0;
    }

    static void Note(string what) { todos[what] = todos.TryGetValue(what, out var c) ? c + 1 : 1; }

    static string Todo(string what)
    {
        todos[what] = todos.TryGetValue(what, out var c) ? c + 1 : 1;
        throw new Todo(what);
    }

