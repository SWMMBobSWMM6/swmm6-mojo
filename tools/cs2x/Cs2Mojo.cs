    static string Id(string n)
    {
        n = n.TrimStart('@');
        if (Reserved.Contains(n)) return n + "_";
        return n;
    }

    static bool IsRuntime(ISymbol s)
    {
        var ns = s is INamespaceSymbol nss ? nss : s.ContainingNamespace;
        while (ns != null && !ns.IsGlobalNamespace)
        {
            if (ns.Name == "Cpp" && ns.ContainingNamespace.IsGlobalNamespace) return true;
            ns = ns.ContainingNamespace;
        }
        return false;
    }

    static bool IsSystem(ISymbol s)
    {
        var ns = s.ContainingNamespace;
        while (ns != null && !ns.IsGlobalNamespace) { if (ns.Name == "System" && ns.ContainingNamespace.IsGlobalNamespace) return true; ns = ns.ContainingNamespace; }
        return false;
    }

    static readonly Dictionary<ISymbol, string> typeNames = new(SymbolEqualityComparer.Default);

    static string TypeIdent(INamedTypeSymbol t)
    {
        t = t.OriginalDefinition;
        if (typeNames.TryGetValue(t, out var n)) return n;
        var parts = new List<string>();
        for (var c = t; c != null; c = c.ContainingType) parts.Insert(0, c.Name);
        var ns = new List<string>();
        for (var x = t.ContainingNamespace; x != null && !x.IsGlobalNamespace; x = x.ContainingNamespace) ns.Insert(0, x.Name);
        if (ns.Count > 0 && (ns[0] == "openswmm" || ns[0] == "_global" || ns[0] == "Gen")) ns.RemoveAt(0);
        var s = "T_" + string.Join("_", ns.Concat(parts));
        typeNames[t] = s;
        return s;
    }

    static string NsPrefix(INamedTypeSymbol t)
    {
        if (t.Name == "_F" && t.ContainingType == null)
        {
            var ns = new List<string>();
            for (var x = t.ContainingNamespace; x != null && !x.IsGlobalNamespace; x = x.ContainingNamespace) ns.Insert(0, x.Name);
            if (ns.Count > 0 && (ns[0] == "openswmm" || ns[0] == "_global")) ns.RemoveAt(0);
            return "F_" + string.Join("_", ns);
        }
        return TypeIdent(t);
    }

    static string FuncName(IMethodSymbol m) => NsPrefix(m.ContainingType.OriginalDefinition) + "__" + MethodIdent(m);

    static string StaticFieldName(IFieldSymbol f) => "gs()[]." + StaticFieldIdent(f);
    static string StaticFieldIdent(IFieldSymbol f) => "G_" + NsPrefix(f.ContainingType.OriginalDefinition) + "__" + f.Name.TrimStart('@');

    static readonly Dictionary<IMethodSymbol, string> methodNames = new(SymbolEqualityComparer.Default);

    static string MethodIdent(IMethodSymbol m)
    {
        m = m.OriginalDefinition;
        if (methodNames.TryGetValue(m, out var n)) return n;
        var t = m.ContainingType;
        var same = t.GetMembers(m.Name).OfType<IMethodSymbol>().Where(x => x.MethodKind == MethodKind.Ordinary).ToList();
        var nm = m.Name.TrimStart('@');
        if (same.Count > 1)
            nm += "__" + string.Join("_", m.Parameters.Select(p => ShortType(p.Type) + (p.RefKind != RefKind.None ? "r" : "")));
        methodNames[m] = nm;
        return nm;
    }

    static string ShortType(ITypeSymbol t)
    {
        switch (t.SpecialType)
        {
            case SpecialType.System_Int32: return "i";
            case SpecialType.System_Int64: return "l";
            case SpecialType.System_UInt64: return "ul";
            case SpecialType.System_UInt32: return "u";
            case SpecialType.System_Double: return "d";
            case SpecialType.System_Single: return "f";
            case SpecialType.System_Boolean: return "b";
            case SpecialType.System_SByte: return "c";
            case SpecialType.System_Byte: return "uc";
            case SpecialType.System_Int16: return "s";
            case SpecialType.System_UInt16: return "us";
            case SpecialType.System_Object: return "o";
            case SpecialType.System_String: return "str";
        }
        if (t is IArrayTypeSymbol at) return ShortType(at.ElementType) + "A";
        if (t is ITypeParameterSymbol tp) return tp.Name;
        if (t is INamedTypeSymbol nt)
        {
            var s = nt.Name;
            if (nt.TypeArguments.Length > 0) s += string.Join("", nt.TypeArguments.Select(ShortType));
            return s;
        }
        return "x";
    }

    static string FieldIdent(IFieldSymbol f) => Id(f.Name);

    // ------------------------------------------------------------------------------------------------ hierarchy
    static readonly HashSet<INamedTypeSymbol> hasDerived = new(SymbolEqualityComparer.Default);
    static readonly List<INamedTypeSymbol> engineTypes = new();
    static readonly Dictionary<INamedTypeSymbol, int> tids = new(SymbolEqualityComparer.Default);

    static bool IsEngine(ITypeSymbol? t) => t is INamedTypeSymbol n && !IsRuntime(n) && !IsSystem(n) && n.Locations.Any(l => l.IsInSource);

    static void CollectTypes(List<SyntaxTree> gen)
    {
        var seen = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var t in gen)
            foreach (var td in t.GetRoot().DescendantNodes().OfType<BaseTypeDeclarationSyntax>())
            {
                var s = (INamedTypeSymbol)M(td).GetDeclaredSymbol(td)!;
                if (seen.Add(s)) engineTypes.Add(s);
            }
        foreach (var s in engineTypes)
            for (var b = s.BaseType; b != null && IsEngine(b); b = b.BaseType) hasDerived.Add(b.OriginalDefinition);
        int next = 1000;
        foreach (var s in engineTypes.OrderBy(x => TypeIdent(x), StringComparer.Ordinal))
            if (s.TypeKind == TypeKind.Class && !s.IsStatic && InHierarchy(s)) tids[s.OriginalDefinition] = next++;
    }

    static bool InHierarchy(INamedTypeSymbol t)
    {
        t = t.OriginalDefinition;
        if (hasDerived.Contains(t)) return true;
        var b = t.BaseType;
        return b != null && b.SpecialType != SpecialType.System_Object && (IsEngine(b) || IsRuntime(b));
    }

    /// <summary>The path from an object of type t (seen through `[]`) to its type id field.</summary>
    static string TidPath(INamedTypeSymbol t)
    {
        var s = new StringBuilder();
        var c = t.OriginalDefinition;
        while (true)
        {
            var b = c.BaseType;
            if (b != null && IsEngine(b)) { s.Append(".__base"); c = b.OriginalDefinition; continue; }
            if (b != null && IsRuntime(b)) { s.Append(".__base.tid"); return s.ToString(); }
            s.Append(".__tid");
            return s.ToString();
        }
    }

    static int Tid(INamedTypeSymbol t) => tids.TryGetValue(t.OriginalDefinition, out var v) ? v : Todo("type id of " + t.Name) is var _ ? 0 : 0;

    static readonly Dictionary<string, int> runtimeExcKinds = new()
    {
        ["CppException"] = 1, ["LogicError"] = 2, ["RuntimeError"] = 3, ["InvalidArgument"] = 4, ["OutOfRange"] = 5,
        ["LengthError"] = 6, ["DomainError"] = 7, ["RangeError"] = 8, ["OverflowError"] = 9, ["BadAlloc"] = 10,
        ["BadOptionalAccess"] = 11, ["BadFunctionCall"] = 12, ["BadVariantAccess"] = 13,
        ["Exception"] = 100, ["NotImplementedException"] = 101, ["InvalidOperationException"] = 102,
        ["NotSupportedException"] = 103, ["ArgumentException"] = 104, ["IndexOutOfRangeException"] = 105,
    };

    static bool IsExceptionType(ITypeSymbol t)
    {
        for (var b = t as INamedTypeSymbol; b != null; b = b.BaseType)
            if ((IsRuntime(b) && b.Name == "CppException") || (IsSystem(b) && b.Name == "Exception")) return true;
        return false;
    }

    static int TargetTid(INamedTypeSymbol t)
    {
        if (IsEngine(t)) return Tid(t);
        if (runtimeExcKinds.TryGetValue(t.Name, out var k)) return k;
        return Todo("type id of " + t.ToDisplayString()) is var _ ? 0 : 0;
    }

    static string TypeIdTables()
    {
        var sb = new StringBuilder("# ---------------------------------------------------------------- type ids\n");
        sb.Append("def __tid_parent(t: UInt32) -> UInt32:\n");
        foreach (var g in tids.OrderBy(k => k.Value).GroupBy(kv =>
        {
            var b = kv.Key.BaseType;
            if (b != null && IsEngine(b)) return Tid(b);
            if (b != null && IsRuntime(b)) return runtimeExcKinds.TryGetValue(b.Name, out var k) ? k : 0;
            return 0;
        }))
        {
            var ids = g.Select(kv => kv.Value).ToList();
            sb.Append("    if ").Append(string.Join(" or ", ids.Select(i => "t == " + i))).Append(":\n        return ").Append(g.Key).Append('\n');
        }
        sb.Append("    return exc_parent(t)\n\n");
        sb.Append("def __isA(t0: UInt32, target: UInt32) -> Bool:\n    var t = t0\n    while t != 0:\n        if t == target:\n            return True\n        t = __tid_parent(t)\n    return False\n\n");
        return sb.ToString();
    }

    // ------------------------------------------------------------------------------------------------ types
    public static string MojoType(ITypeSymbol t)
    {
        switch (t.SpecialType)
        {
            case SpecialType.System_Boolean: return "Bool";
            case SpecialType.System_SByte: return "Int8";
            case SpecialType.System_Byte: return "UInt8";
            case SpecialType.System_Int16: return "Int16";
            case SpecialType.System_UInt16: return "UInt16";
            case SpecialType.System_Int32: return "Int32";
            case SpecialType.System_UInt32: return "UInt32";
            case SpecialType.System_Int64: return "Int64";
            case SpecialType.System_UInt64: return "UInt64";
            case SpecialType.System_Single: return "Float32";
            case SpecialType.System_Double: return "Float64";
            case SpecialType.System_Char: return "UInt16";
            case SpecialType.System_String: return "CStr";
            case SpecialType.System_Object: return "Obj";
            case SpecialType.System_Void: return "NoneType";
            case SpecialType.System_IntPtr: return "Int";
        }
        if (t is IArrayTypeSymbol at)
        {
            if (at.Rank != 1) Todo("multidimensional array");
            return "Ary[" + MojoType(at.ElementType) + "]";
        }
        if (t is ITypeParameterSymbol tp) return tp.Name;
        if (t is INamedTypeSymbol n)
        {
            if (n.TypeKind == TypeKind.Delegate) return "Dlg";
            if (IsRuntime(n)) return RuntimeType(n);
            if (IsSystem(n))
            {
                if (IsExceptionType(n)) return "Ref[CppException]";
                if (n.Name == "IDisposable") return "Obj";
                if (n.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T) return MojoType(n.TypeArguments[0]);
                return Todo("system type " + n.ToDisplayString());
            }
            if (n.TypeKind == TypeKind.Enum) return TypeIdent(n);
            if (n.TypeKind == TypeKind.Interface) return Todo("engine interface type " + n.Name);
            return "Ref[" + TypeIdent(n) + "]";
        }
        return Todo("type " + t.ToDisplayString());
    }

    static string RuntimeType(INamedTypeSymbol n)
    {
        var name = StripArity(n.Name);
        if (name == "Raw") return "NoneType";
        if (IsExceptionType(n)) return "Ref[CppException]";
        if (name is "IStringStream" or "IFStream" or "IStream" or "IosBase") return "Ref[IStream]";
        if (name is "OStringStream" or "OFStream" or "OStream") return "Ref[OStream]";
        var s = RuntimeTypeName(n);
        Use("type " + n.OriginalDefinition.ToDisplayString(), s);
        return n.TypeKind == TypeKind.Struct || n.TypeKind == TypeKind.Enum ? s : "Ref[" + s + "]";
    }

    /// <summary>The runtime's Mojo struct, without the Ref of a class: Vec[Float64], Str.</summary>
    static string RuntimeTypeName(INamedTypeSymbol n)
    {
        var parts = new List<string>();
        for (var c = n; c != null; c = c.ContainingType) parts.Insert(0, StripArity(c.Name));
        var s = string.Join("_", parts);
        if (s is "IStringStream" or "IFStream" or "IosBase") s = "IStream";
        if (s is "OStringStream" or "OFStream") s = "OStream";
        // the hasher and key-equal of UMapC/USetC are engine types given as types, not references
        if (n.TypeArguments.Length > 0) s += "[" + string.Join(", ", n.TypeArguments.Select((a, i) =>
            (s is "UMapC" && i >= 2) || (s is "USetC" && i >= 1) ? TypeIdent((INamedTypeSymbol)a) : MojoType(a))) + "]";
        return s;
    }

    static string StripArity(string s) { var i = s.IndexOf('`'); return i < 0 ? s : s.Substring(0, i); }

    static void Use(string key, string m) { manifest[key] = m; }

    static string ParamType(IParameterSymbol p) => p.RefKind != RefKind.None ? "P[" + MojoType(p.Type) + "]" : MojoType(p.Type);
    static string RetType(IMethodSymbol m) => m.ReturnsVoid ? "NoneType" : m.RefKind != RefKind.None ? "P[" + MojoType(m.ReturnType) + "]" : MojoType(m.ReturnType);
    static string RetSuffix(string r) => r == "NoneType" ? "" : " -> " + r;

    // ------------------------------------------------------------------------------------------------ declarations
    static void TypeDecl(BaseTypeDeclarationSyntax td, StringBuilder sb, HashSet<INamedTypeSymbol> declared)
    {
        var s = (INamedTypeSymbol)M(td).GetDeclaredSymbol(td)!;
        if (td is EnumDeclarationSyntax)
        {
            if (!declared.Add(s)) return;
            var ut = MojoType(s.EnumUnderlyingType!);
            var nm = TypeIdent(s);
            sb.Append("comptime ").Append(nm).Append(" = ").Append(ut).Append('\n');
            foreach (var f in s.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue))
                sb.Append("comptime ").Append(nm).Append("__").Append(f.Name.TrimStart('@')).Append(" = ").Append(ut).Append('(').Append(IntLit(f.ConstantValue!)).Append(")\n");
            sb.Append('\n');
            return;
        }
        if (td is not ClassDeclarationSyntax cd) { Note("type declaration " + td.Kind()); return; }
        if (!s.IsStatic && declared.Add(s)) StructDecl(s, sb);
        foreach (var m in cd.Members)
        {
            var mark = funcs.Length;
            try
            {
                switch (m)
                {
                    case MethodDeclarationSyntax md: MethodDecl(md, s); break;
                    case ConstructorDeclarationSyntax ctor: CtorDecl(ctor, s); break;
                    case FieldDeclarationSyntax fd: StaticFieldDecl(fd, s); break;
                    case BaseTypeDeclarationSyntax: break;
                    case DelegateDeclarationSyntax: break;
                    default: Note("member " + m.Kind()); break;
                }
            }
            catch (Todo e) { funcs.Length = mark; funcs.Append("# TODO ").Append(e.Message.Replace("\n", " ")).Append('\n'); }
            catch (Exception e) when (e is not global::Todo)
            {
                funcs.Length = mark;
                funcs.Append("# TODO translator error: ").Append(e.GetType().Name).Append(' ').Append(e.Message.Replace("\n", " ")).Append('\n');
                Note("translator error " + e.GetType().Name + " " + e.Message.Split('\n')[0]);
            }
        }
    }

    static IMethodSymbol? FindMethod(INamedTypeSymbol s, string name, int nparams) =>
        s.GetMembers(name).OfType<IMethodSymbol>().FirstOrDefault(m => m.Parameters.Length == nparams && !m.IsStatic && m.MethodKind == MethodKind.Ordinary);

    static bool Implements(INamedTypeSymbol s, string iface) => s.AllInterfaces.Any(i => (IsRuntime(i) || IsSystem(i)) && StripArity(i.Name) == iface);

    static void StructDecl(INamedTypeSymbol s, StringBuilder sb)
    {
        var nm = TypeIdent(s);
        var hashOf0 = FindMethod(s, "HashOf", 1);
        var call20 = FindMethod(s, "Call2", 2);
        var traits = "EStruct" + (hashOf0 != null && hashOf0.Parameters[0].Type.Name == "Str" ? ", KeyHash" : "") + (call20 != null && call20.Parameters[0].Type.Name == "Str" ? ", KeyEq" : "");
        sb.Append("struct ").Append(nm).Append("(").Append(traits).Append("):\n");
        var b = s.BaseType;
        int nf = 0;
        if (b != null && IsEngine(b)) { sb.Append("    var __base: ").Append(TypeIdent(b)).Append('\n'); nf++; }
        else if (b != null && IsRuntime(b))
        {
            if (!IsExceptionType(b)) Todo("engine class " + s.Name + " derives from runtime class " + b.Name);
            sb.Append("    var __base: CppException\n"); nf++;
        }
        else if (InHierarchy(s)) { sb.Append("    var __tid: UInt32\n"); nf++; }
        foreach (var f in s.GetMembers().OfType<IFieldSymbol>().Where(f => !f.IsStatic && !f.IsConst))
        {
            string mt;
            try { mt = MojoType(f.Type); } catch (Todo e) { mt = "Obj  # TODO " + e.Message; }
            sb.Append("    var ").Append(FieldIdent(f)).Append(": ").Append(mt).Append('\n'); nf++;
        }
        if (nf == 0) sb.Append("    var __empty: UInt8\n");
        // the runtime's protocol (rt.core EStruct): how a container makes, copies, assigns, moves, compares and
        // destroys an element of this class
        var self = "Ref[Self]";
        bool isCopy = s.AllInterfaces.Any(i => IsRuntime(i) && StripArity(i.Name) == "ICopy");
        if (isCopy) sb.Append("    comptime IS_CLASS = True\n");
        if (!s.IsAbstract && s.InstanceConstructors.Any(c => c.Parameters.Length == 0 && c.DeclaringSyntaxReferences.Length > 0))
            sb.Append("    @staticmethod\n    def __new() raises -> ").Append(self).Append(":\n        return ").Append(nm).Append("__new()\n");
        var clone = FindMethod(s, "Clone", 0);
        if (clone != null) sb.Append("    @staticmethod\n    def __clone(x: ").Append(self).Append(") raises -> ").Append(self).Append(":\n        return ").Append(FuncName(clone)).Append("(x)\n");
        var assign = s.GetMembers("Assign").OfType<IMethodSymbol>().FirstOrDefault(m => m.Parameters.Length == 1 && SymbolEqualityComparer.Default.Equals(m.Parameters[0].Type.OriginalDefinition, s.OriginalDefinition));
        if (assign != null) sb.Append("    @staticmethod\n    def __assign(d: ").Append(self).Append(", x: ").Append(self).Append(") raises:\n        ").Append(FuncName(assign)).Append("(d, x)\n");
        var move = s.GetMembers("MoveFrom").OfType<IMethodSymbol>().FirstOrDefault(m => m.Parameters.Length == 1 && SymbolEqualityComparer.Default.Equals(m.Parameters[0].Type.OriginalDefinition, s.OriginalDefinition));
        if (move != null) sb.Append("    @staticmethod\n    def __moveFrom(d: ").Append(self).Append(", x: ").Append(self).Append(") raises:\n        ").Append(FuncName(move)).Append("(d, x)\n");
        if (NeedsDisposeDispatch(s)) sb.Append("    @staticmethod\n    def __dispose(x: ").Append(self).Append(") raises:\n        ").Append(DisposeFn(s)).Append("(x)\n");
        var cmp = s.GetMembers("CompareTo").OfType<IMethodSymbol>().FirstOrDefault(m => m.Parameters.Length == 1 && !m.IsStatic);
        if (cmp != null && SymbolEqualityComparer.Default.Equals(cmp.Parameters[0].Type.OriginalDefinition, s.OriginalDefinition))
            sb.Append("    @staticmethod\n    def __less(a: ").Append(self).Append(", b: ").Append(self).Append(") raises -> Bool:\n        return ").Append(FuncName(cmp)).Append("(a, b) < 0\n");
        var hashOf = FindMethod(s, "HashOf", 1);
        if (hashOf != null && hashOf.Parameters[0].Type.Name == "Str")
            sb.Append("    @staticmethod\n    def __hash_str(k: Ref[Str]) raises -> UInt64:\n        return ").Append(FuncName(hashOf)).Append("(").Append(self).Append("(), k)\n");
        var call2 = FindMethod(s, "Call2", 2);
        if (call2 != null && call2.Parameters[0].Type.Name == "Str")
            sb.Append("    @staticmethod\n    def __eq_str(a: Ref[Str], b: Ref[Str]) raises -> Bool:\n        return ").Append(FuncName(call2)).Append("(").Append(self).Append("(), a, b)\n");
        sb.Append('\n');
        if (s.TypeKind == TypeKind.Class)
        {
            var raw = new StringBuilder();
            raw.Append("def ").Append(nm).Append("__raw() raises -> Ref[").Append(nm).Append("]:\n    var o = Ref[").Append(nm).Append("](gc_new[").Append(nm).Append("]())\n");
            if (tids.ContainsKey(s.OriginalDefinition)) raw.Append("    o[]").Append(TidPath(s)).Append(" = ").Append(Tid(s)).Append('\n');
            var root = s; var path = "";
            while (root.BaseType != null && IsEngine(root.BaseType)) { root = root.BaseType; path += ".__base"; }
            if (root.BaseType != null && IsRuntime(root.BaseType)) raw.Append("    o[]").Append(path).Append(".__base.init_default()\n");
            raw.Append("    return o\n\n");
            funcs.Append(raw);
        }
    }

    static bool HasDispose(INamedTypeSymbol s) => Implements(s, "IDisposable") && FindMethod(s, "Dispose", 0) != null;

    static IEnumerable<INamedTypeSymbol> Descendants(INamedTypeSymbol s) =>
        engineTypes.Where(x => x.TypeKind == TypeKind.Class && !x.IsStatic && DerivesOrSame(x, s));

    static bool DerivesOrSame(INamedTypeSymbol d, INamedTypeSymbol b)
    {
        for (INamedTypeSymbol? x = d; x != null; x = x.BaseType) if (SymbolEqualityComparer.Default.Equals(x.OriginalDefinition, b.OriginalDefinition)) return true;
        return false;
    }

    static bool NeedsDisposeDispatch(INamedTypeSymbol s) => Descendants(s).Any(HasDispose);

    static readonly HashSet<string> disposeFns = new();

    static string DisposeFn(INamedTypeSymbol s)
    {
        var nm = TypeIdent(s) + "____dispose";
        if (!disposeFns.Add(nm)) return nm;
        var f = new StringBuilder();
        f.Append("def ").Append(nm).Append("(o: Ref[").Append(TypeIdent(s)).Append("]) raises:\n    if o.isnull():\n        return\n");
        if (tids.ContainsKey(s.OriginalDefinition))
        {
            f.Append("    var t = o[]").Append(TidPath(s)).Append('\n');
            foreach (var d in Descendants(s).Where(HasDispose))
            {
                var m = FindMethod(d, "Dispose", 0)!;
                f.Append("    if t == ").Append(Tid(d)).Append(":\n        ").Append(FuncName(m)).Append("(o.cast[").Append(TypeIdent(d)).Append("]())\n        return\n");
            }
        }
        else f.Append("    ").Append(FuncName(FindMethod(s, "Dispose", 0)!)).Append("(o)\n");
        f.Append('\n');
        funcs.Append(f);
        return nm;
    }

    static string BasePath(INamedTypeSymbol d, INamedTypeSymbol b)
    {
        var s = new StringBuilder();
        for (var x = d.OriginalDefinition; !SymbolEqualityComparer.Default.Equals(x, b.OriginalDefinition); x = x.BaseType!.OriginalDefinition) s.Append(".__base");
        return s.ToString();
    }

    static string IntLit(object v) => v switch
    {
        int i => i.ToString(), long l => l.ToString(), uint u => u.ToString(), ulong ul => ul.ToString(),
        short sh => sh.ToString(), ushort us => us.ToString(), byte by => by.ToString(), sbyte sb => sb.ToString(),
        char ch => ((int)ch).ToString(),
        _ => v.ToString()!
    };

    static void StaticFieldDecl(FieldDeclarationSyntax fd, INamedTypeSymbol s)
    {
        foreach (var v in fd.Declaration.Variables)
        {
            var f = (IFieldSymbol)M(fd).GetDeclaredSymbol(v)!;
            if (!f.IsStatic || f.IsConst) continue;
            var mt = MojoType(f.Type);
            statics.Append("    var ").Append(StaticFieldIdent(f)).Append(": ").Append(mt).Append('\n');
            if (v.Initializer == null) continue;
            var fi = M(fd).GetOperation(v.Initializer) as IFieldInitializerOperation;
            var op = fi?.Value ?? M(fd).GetOperation(v.Initializer.Value);
            if (op == null) { staticInit.Add("    pass  # TODO initializer of " + f.Name + "\n"); Note("static initializer"); continue; }
            var ctx = new Fn(null, s, "NoneType");
            try
            {
                var lines = new List<string>();
                ctx.AssignInto(StaticFieldName(f), op, f.Type, lines, 1);
                staticInit.Add(string.Concat(lines.Select(l => l + "\n")));
            }
            catch (Todo e) { staticInit.Add("    pass  # TODO initializer of " + f.Name + ": " + e.Message.Replace("\n", " ") + "\n"); }
        }
    }

    static void MethodDecl(MethodDeclarationSyntax md, INamedTypeSymbol s)
    {
        var m = (IMethodSymbol)M(md).GetDeclaredSymbol(md)!;
        if (m.IsAbstract || (md.Body == null && md.ExpressionBody == null)) return;
        var fn = new Fn(m, s, RetType(m));
        IOperation? op = md.Body != null ? M(md).GetOperation(md.Body) : M(md).GetOperation(md.ExpressionBody!);
        string body = op == null ? "    pass\n" : fn.Body(op, m.Parameters, !m.IsStatic);
        var ps = new List<string>();
        if (!m.IsStatic) ps.Add("this: Ref[" + TypeIdent(s) + "]");
        foreach (var p in m.Parameters) ps.Add(fn.ParamDecl(p));
        funcs.Append("def ").Append(FuncName(m)).Append('(').Append(string.Join(", ", ps)).Append(") raises").Append(RetSuffix(RetType(m))).Append(":\n").Append(body).Append('\n');
        if (m.IsVirtual && !m.IsOverride && tids.ContainsKey(s.OriginalDefinition)) VDispatch(m);
    }

    static void CtorDecl(ConstructorDeclarationSyntax cd, INamedTypeSymbol s)
    {
        var c = (IMethodSymbol)M(cd).GetDeclaredSymbol(cd)!;
        if (c.IsStatic) { Todo("static constructor"); return; }
        var nm = TypeIdent(s);
        if (c.Parameters.Length == 1 && c.Parameters[0].Type.Name == "Raw")
        {
            if (cd.Body != null && cd.Body.Statements.Count > 0) Todo("raw constructor with a body in " + s.Name);
            return;
        }
        if (c.Parameters.Length != 0) { Todo("constructor with parameters in " + s.Name); return; }
        if (s.IsAbstract) return;
        var init = cd.Initializer;
        if (init != null && !(init.ThisOrBaseKeyword.IsKind(SyntaxKind.ThisKeyword) && init.ArgumentList.Arguments.Count == 1))
            Todo("constructor initializer in " + s.Name);
        var fn = new Fn(c, s, "Ref[" + nm + "]");
        string body = "";
        if (cd.Body != null && cd.Body.Statements.Count > 0) body = fn.Body(M(cd).GetOperation(cd.Body)!, c.Parameters, true, true);
        funcs.Append("def ").Append(nm).Append("__new() raises -> Ref[").Append(nm).Append("]:\n    var this = ").Append(nm).Append("__raw()\n")
            .Append(body).Append(fn.ReturnPrefix("    ")).Append("    return this\n\n");
    }

    // ---- virtual calls: a dispatcher per root virtual method, testing the type id
    static readonly HashSet<string> vdispatch = new();

    public static IMethodSymbol VRoot(IMethodSymbol m)
    {
        m = m.OriginalDefinition;
        while (m.OverriddenMethod != null) m = m.OverriddenMethod.OriginalDefinition;
        return m;
    }

    public static string VDispatch(IMethodSymbol m)
    {
        var root = VRoot(m);
        var b = root.ContainingType.OriginalDefinition;
        var name = FuncName(root) + "__v";
        if (!vdispatch.Add(name)) return name;
        if (!IsEngine(b)) Todo("virtual method of a runtime class: " + root.ToDisplayString());
        var f = new StringBuilder();
        var ps = new List<string> { "o: Ref[" + TypeIdent(b) + "]" };
        var args = new List<string>();
        int i = 0;
        foreach (var p in root.Parameters) { ps.Add("a" + i + ": " + ParamType(p)); args.Add("a" + i); i++; }
        f.Append("@no_inline\ndef ").Append(name).Append('(').Append(string.Join(", ", ps)).Append(") raises").Append(RetSuffix(RetType(root))).Append(":\n");
        f.Append("    var t = o[]").Append(TidPath(b)).Append('\n');
        var groups = new Dictionary<IMethodSymbol, List<INamedTypeSymbol>>(SymbolEqualityComparer.Default);
        foreach (var d in Descendants(b).Where(x => !x.IsAbstract))
        {
            IMethodSymbol? impl = null;
            for (INamedTypeSymbol? x = d; x != null && impl == null; x = x.BaseType)
            {
                foreach (var cand in x.GetMembers(root.Name).OfType<IMethodSymbol>())
                {
                    if (cand.IsAbstract) continue;
                    if (SymbolEqualityComparer.Default.Equals(cand.OriginalDefinition, root) || (cand.IsOverride && SymbolEqualityComparer.Default.Equals(VRoot(cand), root)))
                    { impl = cand.OriginalDefinition; break; }
                }
                if (SymbolEqualityComparer.Default.Equals(x.OriginalDefinition, b)) break;
            }
            if (impl == null) continue;
            if (!groups.TryGetValue(impl, out var l)) groups[impl] = l = new List<INamedTypeSymbol>();
            l.Add(d);
        }
        foreach (var kv in groups)
        {
            var impl = kv.Key;
            var it = impl.ContainingType.OriginalDefinition;
            f.Append("    if ").Append(string.Join(" or ", kv.Value.Select(x => "t == " + Tid(x)))).Append(":\n        return ").Append(FuncName(impl)).Append('(')
             .Append(SymbolEqualityComparer.Default.Equals(it, b) ? "o" : "o.cast[" + TypeIdent(it) + "]()");
            foreach (var a in args) f.Append(", ").Append(a);
            f.Append(")\n");
        }
        f.Append("    raise rt_unreachable()\n\n");
        funcs.Append(f);
        return name;
    }

    // ---- delegates: one dispatcher per Mojo signature, testing the delegate's number
    static readonly SortedDictionary<string, List<(int id, string fn)>> dispatch = new(StringComparer.Ordinal);
    static readonly Dictionary<string, (List<string> ps, string ret)> dispatchSig = new();
    static readonly Dictionary<string, string> dispatchNames = new();
    static int nextDelegateId = 1;

    /// <summary>The dispatcher of a signature (parameter Mojo types and return type), registering it.</summary>
    static string DispatcherOf(List<string> ps, string ret)
    {
        var key = string.Join(", ", ps) + " -> " + ret;
        if (!dispatchNames.TryGetValue(key, out var n))
        {
            n = "__call" + dispatchNames.Count;
            dispatchNames[key] = n;
            dispatchSig[n] = (ps, ret);
            dispatch[n] = new List<(int, string)>();
        }
        return n;
    }

    static int AddTarget(string disp, string fn)
    {
        var id = nextDelegateId++;
        dispatch[disp].Add((id, fn));
        return id;
    }

    static string Dispatchers()
    {
        var sb = new StringBuilder("# ---------------------------------------------------------------- delegate dispatchers\n");
        foreach (var kv in dispatch)
        {
            var (ps, ret) = dispatchSig[kv.Key];
            var decl = new List<string> { "d: Dlg" };
            var args = new List<string> { "d.ctx" };
            for (int i = 0; i < ps.Count; i++) { decl.Add("a" + i + ": " + ps[i]); args.Add("a" + i); }
            // never inlined, so that a dispatcher's targets are not copied into every call of a delegate
            sb.Append("@no_inline\ndef ").Append(kv.Key).Append('(').Append(string.Join(", ", decl)).Append(") raises").Append(RetSuffix(ret)).Append(":\n");
            foreach (var (id, fn) in kv.Value)
                sb.Append("    if d.id == ").Append(id).Append(":\n        return ").Append(fn).Append('(').Append(string.Join(", ", args)).Append(")\n");
            sb.Append("    raise rt_bad_function_call()\n\n");
        }
        return sb.ToString();
    }

    static string Cap(string s) => s.Length == 0 ? s : char.ToUpperInvariant(s[0]) + s.Substring(1);
