// Cs2Mojo - translate the generated C# SWMM6 engine (cs/gen) into Mojo 1.2 (mojo/gen/engine.mojo), using Roslyn's
// semantic model. See MOJO.md for the mapping.
//
// The C# engine (cs/gen) is the C++ engine translated by tools/cpp2x and held byte for byte to the C++ reference by
// gate/gate.py. This program reads it with the compiler's semantic model and writes the same program in Mojo:
// classes become structs reached through rt.Ref (a pointer), inheritance an embedded base struct and a type id,
// virtual calls a chain of tests on the type id, exceptions Mojo `raises` with the thrown object held by the runtime,
// lambdas functions with a context of pointers, delegates a context and a number dispatched per signature (Mojo 1.2
// cannot keep a function in a struct field), static fields one struct at a fixed address (Mojo 1.2 has no global
// variables), and the C# runtime (namespace Cpp) the Mojo runtime in mojo/rt. The design follows the Zig back end
// (Cs2Zig.cs and its companions), whose structure this one copies.
//
//   dotnet bin/cs2mojo.dll CS_DIR MOJO_GEN_DIR
//
// Written by Claude (Anthropic) for the SWMM6 ports; see AI-USE.md.
