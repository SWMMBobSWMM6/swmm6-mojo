#!/bin/sh
# Write mojo/rt/primes.mojo, libstdc++'s std::__detail::__prime_list, from the C# runtime's cs/runtime/PrimeList.cs
# (which tests/stdcheck/primes.cpp extracted from the system libstdc++). Mojo 1.2 has no global arrays, so the list is
# written into a block at the first call and read from there.
# Written by Claude (Anthropic) for Robert Dickinson's SWMM6 ports; see AI-USE.md and mojo/README.md.
set -e
cd "$(dirname "$0")"
N=$(grep -E '^[0-9]' ../cs/runtime/PrimeList.cs | tr ',' '\n' | grep -c 'UL')
{
  echo "# primes.mojo - libstdc++'s __prime_list (from cs/runtime/PrimeList.cs), for the hash tables' rehash policy."
  echo "# Generated by mojo/make_primes.sh. Written by Claude (Anthropic) for the SWMM6 ports; see AI-USE.md."
  echo ""
  echo "from rt.core import *"
  echo ""
  echo "comptime N_PRIMES = $N"
  echo ""
  echo ""
  echo "def PRIMES(i: Int) -> UInt64:"
  echo "    var t = P[UInt64](unsafe_from_address=rts()[].primes)"
  echo "    if Int(t) == 0:"
  echo "        t = _build()"
  echo "    return t[unsafe_offset=i]"
  echo ""
  echo ""
  echo "def _build() -> P[UInt64]:"
  echo "    var t = gc_array[UInt64]($N)"
  grep -E '^[0-9]' ../cs/runtime/PrimeList.cs | tr ',' '\n' | grep 'UL' | sed -E 's/ //g; s/UL//' | awk '{print "    t[unsafe_offset=" NR-1 "] = " $1}'
  echo "    rts()[].primes = Int(t)"
  echo "    return t"
} > "${1:-rt/primes.mojo}"
